"""Generate explicit stored routines for the confirmed SQL; never derives names from HTTP input."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = {
    'sedes': [('nombre', 'text'), ('ciudad', 'text')],
    'docentes': [('usuario_id', 'integer'), ('cvlac_url', 'text'), ('escalafon', 'text'), ('minciencias_categoria', 'text')],
    'grupos_investigacion': [('sede_id', 'integer'), ('gruptac_url', 'text'), ('categoria', 'text')],
    'semilleros': [('grupo_id', 'integer'), ('nombre', 'text'), ('descripcion', 'text')],
    'lineas_investigacion': [('codigo', 'text'), ('nombre', 'text'), ('descripcion', 'text')],
    'grupo_docentes': [('grupo_id', 'integer'), ('docente_id', 'integer'), ('rol', 'text'), ('fecha_inicio', 'date'), ('fecha_fin', 'date')],
    'semillero_tutores': [('semillero_id', 'integer'), ('docente_id', 'integer'), ('rol', 'text'), ('fecha_inicio', 'date'), ('fecha_fin', 'date')],
    **{name: [('nombre', 'text')] for name in ('areas_conocimiento', 'ods', 'areas_aplicacion', 'palabras_clave')},
}
BRIDGES = {
    'grupo_lineas': ('grupo_id', 'linea_id'),
    'semillero_lineas': ('semillero_id', 'linea_id'),
    'linea_disciplinas': ('linea_id', 'disciplina_id'),
    'linea_ods': ('linea_id', 'ods_id'),
    'linea_aplicacion': ('linea_id', 'aplicacion_id'),
}
STATE = {name: ('activa' if name == 'sedes' else 'activo') for name in FIELDS
         if name not in ('docentes', 'semillero_tutores')}
VIEWS = {
    'docentes': 'SELECT t.*, u.nombre AS usuario_nombre FROM docentes t JOIN usuarios u ON u.id=t.usuario_id',
    'grupos_investigacion': "SELECT t.*, s.nombre AS sede_nombre, s.nombre || ' · Grupo #' || t.id AS etiqueta FROM grupos_investigacion t JOIN sedes s ON s.id=t.sede_id",
    'semilleros': "SELECT t.*, s.nombre || ' · Grupo #' || g.id AS grupo_etiqueta FROM semilleros t JOIN grupos_investigacion g ON g.id=t.grupo_id JOIN sedes s ON s.id=g.sede_id",
    'grupo_docentes': "SELECT t.*, u.nombre AS docente_nombre, s.nombre || ' · Grupo #' || g.id AS grupo_etiqueta FROM grupo_docentes t JOIN docentes d ON d.id=t.docente_id JOIN usuarios u ON u.id=d.usuario_id JOIN grupos_investigacion g ON g.id=t.grupo_id JOIN sedes s ON s.id=g.sede_id",
    'semillero_tutores': 'SELECT t.*, u.nombre AS docente_nombre, s.nombre AS semillero_nombre FROM semillero_tutores t JOIN docentes d ON d.id=t.docente_id JOIN usuarios u ON u.id=d.usuario_id JOIN semilleros s ON s.id=t.semillero_id',
}


def generate():
    sql = ['-- Generated by scripts/generate-research-routines.py. Names and columns follow migration 006.',
           '-- These functions execute with caller privileges; no SECURITY DEFINER or user-supplied identifiers.']
    for table, fields in FIELDS.items():
        active = f't.{STATE[table]}' if table in STATE else 'TRUE'
        sql.append(f'CREATE OR REPLACE VIEW public.v2_{table} AS {VIEWS.get(table, f"SELECT t.* FROM {table} t")};')
        sql.append(f'''CREATE OR REPLACE FUNCTION public.sp_listar_v2_{table}() RETURNS jsonb LANGUAGE sql AS $$
SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id), '[]'::jsonb) FROM public.v2_{table} t WHERE {active};
$$;
CREATE OR REPLACE FUNCTION public.sp_consultar_v2_{table}(p_id integer) RETURNS jsonb LANGUAGE sql AS $$
SELECT to_jsonb(t) FROM public.v2_{table} t WHERE t.id=p_id AND {active};
$$;''')
        columns = ', '.join(name for name, _ in fields)
        values = ', '.join(f"NULLIF(p_datos->>'{name}', '')::{kind}" for name, kind in fields)
        assignments = ', '.join(f"{name}=NULLIF(p_datos->>'{name}', '')::{kind}" for name, kind in fields)
        if table == 'docentes':
            assignments += ', updated_at=CURRENT_TIMESTAMP'
        predicate = f'AND {STATE[table]}' if table in STATE else ''
        sql.append(f'''CREATE OR REPLACE FUNCTION public.sp_crear_v2_{table}(p_datos jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_id integer;
BEGIN
INSERT INTO public.{table} ({columns}) VALUES ({values}) RETURNING id INTO v_id;
RETURN public.sp_consultar_v2_{table}(v_id);
END; $$;
CREATE OR REPLACE FUNCTION public.sp_actualizar_v2_{table}(p_id integer, p_datos jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_id integer;
BEGIN
UPDATE public.{table} SET {assignments} WHERE id=p_id {predicate} RETURNING id INTO v_id;
IF NOT FOUND THEN RETURN NULL; END IF;
RETURN public.sp_consultar_v2_{table}(v_id);
END; $$;''')
        if table in STATE:
            extra = ', deleted_at=CURRENT_TIMESTAMP' if table in ('grupos_investigacion', 'semilleros', 'lineas_investigacion') else ''
            delete = f'UPDATE public.{table} SET {STATE[table]}=FALSE{extra} WHERE id=p_id {predicate}'
        else:
            delete = f'DELETE FROM public.{table} WHERE id=p_id'
        sql.append(f'''CREATE OR REPLACE FUNCTION public.sp_eliminar_v2_{table}(p_id integer) RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
{delete};
RETURN FOUND;
END; $$;''')
    for table, (left, right) in BRIDGES.items():
        sql.append(f'''CREATE OR REPLACE FUNCTION public.sp_listar_v2_{table}() RETURNS jsonb LANGUAGE sql AS $$
SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY {left}, {right}), '[]'::jsonb) FROM public.{table} t;
$$;
CREATE OR REPLACE FUNCTION public.sp_consultar_v2_{table}(p_izquierda integer, p_derecha integer) RETURNS jsonb LANGUAGE sql AS $$
SELECT to_jsonb(t) FROM public.{table} t WHERE {left}=p_izquierda AND {right}=p_derecha;
$$;
CREATE OR REPLACE FUNCTION public.sp_crear_v2_{table}(p_datos jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_row public.{table};
BEGIN
INSERT INTO public.{table} ({left}, {right}) VALUES ((p_datos->>'{left}')::integer, (p_datos->>'{right}')::integer) RETURNING * INTO v_row;
RETURN to_jsonb(v_row);
END; $$;
CREATE OR REPLACE FUNCTION public.sp_eliminar_v2_{table}(p_izquierda integer, p_derecha integer) RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
DELETE FROM public.{table} WHERE {left}=p_izquierda AND {right}=p_derecha;
RETURN FOUND;
END; $$;''')
    sql.append('''CREATE OR REPLACE FUNCTION public.sp_referencias_v2_usuarios() RETURNS jsonb LANGUAGE sql AS $$
SELECT coalesce(jsonb_agg(jsonb_build_object('id', id, 'nombre', nombre) ORDER BY nombre), '[]'::jsonb) FROM public.usuarios;
$$;

-- Preserve the original rule, with a known SQLSTATE and Spanish message instead of a generic 500.
CREATE OR REPLACE FUNCTION public.mira_validar_grupo_activo_semillero() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF NOT EXISTS (SELECT 1 FROM public.grupos_investigacion WHERE id=NEW.grupo_id AND activo AND deleted_at IS NULL FOR SHARE) THEN
    RAISE EXCEPTION 'El semillero debe asociarse a un grupo de investigación activo' USING ERRCODE='23503';
END IF;
RETURN NEW;
END; $$;

CREATE OR REPLACE FUNCTION public.sp_consultar_v2_ficha_grupo(p_id integer) RETURNS jsonb LANGUAGE sql AS $$
SELECT CASE WHEN public.sp_consultar_v2_grupos_investigacion(p_id) IS NULL THEN NULL ELSE
jsonb_build_object('grupo', public.sp_consultar_v2_grupos_investigacion(p_id), 'semilleros',
coalesce((SELECT jsonb_agg(to_jsonb(s) ORDER BY id) FROM public.semilleros s WHERE grupo_id=p_id AND activo), '[]'::jsonb)) END;
$$;

CREATE OR REPLACE FUNCTION public.sp_guardar_v2_ficha_grupo(p_id integer, p_datos jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v_id integer; v_detail jsonb; v_child integer; v_kept integer[] := ARRAY[]::integer[];
BEGIN
IF jsonb_typeof(p_datos->'semilleros') IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'La colección de semilleros es obligatoria' USING ERRCODE='22023';
END IF;
IF p_id IS NULL THEN
    v_id := (public.sp_crear_v2_grupos_investigacion(p_datos->'grupo')->>'id')::integer;
ELSE
    PERFORM 1 FROM public.grupos_investigacion WHERE id=p_id AND activo FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    v_id := (public.sp_actualizar_v2_grupos_investigacion(p_id, p_datos->'grupo')->>'id')::integer;
END IF;
FOR v_detail IN SELECT value FROM jsonb_array_elements(p_datos->'semilleros') LOOP
    v_child := (v_detail->>'id')::integer;
    IF v_child IS NULL THEN
        v_child := (public.sp_crear_v2_semilleros(v_detail || jsonb_build_object('grupo_id',v_id))->>'id')::integer;
    ELSE
        IF v_child=ANY(v_kept) THEN
            RAISE EXCEPTION 'Un semillero aparece repetido en la ficha' USING ERRCODE='23505';
        END IF;
        PERFORM 1 FROM public.semilleros WHERE id=v_child AND grupo_id=v_id AND activo FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'El semillero no pertenece al grupo o está inactivo' USING ERRCODE='23503';
        END IF;
        PERFORM public.sp_actualizar_v2_semilleros(v_child, v_detail || jsonb_build_object('grupo_id',v_id));
    END IF;
    v_kept := array_append(v_kept,v_child);
END LOOP;
UPDATE public.semilleros SET activo=FALSE, deleted_at=CURRENT_TIMESTAMP
WHERE grupo_id=v_id AND activo AND NOT (id=ANY(v_kept));
RETURN public.sp_consultar_v2_ficha_grupo(v_id);
END; $$;
''')
    return '\n\n'.join(sql).rstrip() + '\n'


if __name__ == '__main__':
    (ROOT / 'database/migrations/007_v2_rutinas_investigacion.sql').write_text(generate(), encoding='utf-8')
